def spatial_statistics(image):

    stats = image.reduceRegion(
        reducer=(
            ee.Reducer.mean()
            .combine(
                ee.Reducer.min(),
                sharedInputs=True
            )
            .combine(
                ee.Reducer.max(),
                sharedInputs=True
            )
            .combine(
                ee.Reducer.stdDev(),
                sharedInputs=True
            )
        ),
        geometry=kumasi,
        scale=10000,
        maxPixels=1e9
    )

    return stats.getInfo()

